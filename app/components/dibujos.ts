const normalizar = (t: string) => t.normalize("NFD").replace(/[̀-ͯ]/g, "").toLowerCase().trim();

/** Ruta del dibujo del producto, o null si no hay ninguno (entonces se muestra su emoji). */
export function dibujoDe(nombre: string): string | null {
  const n = normalizar(nombre);
  for (const [regla, clave] of REGLAS) if (regla.test(n)) return `/productos/${clave}.svg`;
  return null;
}
